// shadcn/ui design system for Syra-generated sites.
//
// Every site Syra builds uses shadcn/ui (https://ui.shadcn.com) as its design
// system. Rather than ask the model to reproduce these primitives (slow and
// error-prone), Syra injects the canonical component source, the theme tokens
// (globals.css), the matching tailwind.config.js and the `cn` helper. The model
// then composes the UI by importing from "@/components/ui/*".
//
// All components target Tailwind CSS v3 + the CSS-variable theme below and are
// React 18 compatible (Radix UI primitives).

