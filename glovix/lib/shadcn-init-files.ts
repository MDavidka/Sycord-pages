export function getShadcnFoundationFiles(): Record<string, string> {
  return {
    "lib/utils.ts": SHADCN_UTILS,
    "components.json": SHADCN_COMPONENTS_JSON,
    "app/globals.css": SHADCN_GLOBALS_CSS,
    "tailwind.config.ts": SHADCN_TAILWIND_CONFIG,
  }
}

/** Returns foundation files that are missing from the current project file map. */
export function getMissingShadcnFoundationFiles(
  files: Record<string, { file: { contents: string } }>,
): Record<string, string> {
  const foundation = getShadcnFoundationFiles()
  const missing: Record<string, string> = {}

  for (const [path, content] of Object.entries(foundation)) {
    const existing = files[path]?.file?.contents
    if (!existing || existing.trim().length === 0) {
      missing[path] = content
      continue
    }
    // Upgrade bare globals.css (tailwind directives only) to full token set
    if (path === "app/globals.css" && !existing.includes("--background")) {
      missing[path] = content
    }
    // Upgrade bare tailwind config without shadcn tokens
    if (path === "tailwind.config.ts" && !existing.includes("border-border")) {
      missing[path] = content
    }
  }

  return missing
}
